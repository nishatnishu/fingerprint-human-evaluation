# VALIDATION
# ============================================================

def validate_case():

    # --------------------------------------------------------
    # Human decision
    # --------------------------------------------------------

    if human_decision is None:

        st.error(
            "Please answer the fingerprint comparison question."
        )

        return False


    # --------------------------------------------------------
    # XAI ratings
    # --------------------------------------------------------

    for method in [

        "LIME",

        "Grad-CAM",

        "Integrated Gradients"

    ]:

        if ratings[method]["clarity"] is None:

            st.error(
                f"Please provide a Clarity rating for {method}."
            )

            return False


        if ratings[method]["usefulness"] is None:

            st.error(
                f"Please provide a Usefulness rating for {method}."
            )

            return False


        if ratings[method]["trustworthiness"] is None:

            st.error(
                f"Please provide a Trustworthiness rating for {method}."
            )

            return False


        if ratings[method]["confidence"] is None:

            st.error(
                f"Please provide a Decision Confidence rating for {method}."
            )

            return False


    # --------------------------------------------------------
    # Preferred method
    # --------------------------------------------------------

    if preferred_method is None:

        st.error(
            "Please select your preferred explanation method."
        )

        return False


    return True


