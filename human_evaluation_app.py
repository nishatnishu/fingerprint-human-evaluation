# ============================================================
# PARTICIPANT ID GENERATION
# ============================================================

def generate_participant_id():

    characters = string.ascii_uppercase + string.digits

    code = "".join(
        secrets.choice(characters)
        for _ in range(6)
    )

    return f"P{code}"


